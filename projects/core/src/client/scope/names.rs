//! A name for every kind of request, for the tests of the policy. The names and the
//! match are made from one table: a new request does not compile until it has a name, and
//! the tests fail until it has a sample.

use dusk_protocol::{
    client::{
        CatalogRequest as C, Command as Cmd, GitRequest as G, PluginRequest as Pl,
        ProjectRequest as P, Request as R, SettingsRequest as S, TerminalRequest as Te,
        ThreadRequest as T, VoiceRequest as V, WorkRequest as W,
    },
    plugin::StoreRequest as St,
};

macro_rules! named {
    ($($pattern:pat => $name:literal,)*) => {
        pub fn name(request: &R) -> &'static str {
            match request {
                $($pattern => $name,)*
            }
        }

        pub const NAMES: &[&str] = &[$($name,)*];
    };
}

